"""
Clean the raw synthetic dataset and write Clean_*.csv files plus a Cleaning Log.

Run:  python clean_dataset.py   (after generate_dataset.py)
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "Raw Dataset")
OUT = os.path.join(HERE, "Cleaned Dataset")
os.makedirs(OUT, exist_ok=True)
log = []

# ---------------------------------------------------------------- Customers
c = pd.read_csv(os.path.join(RAW, "Customers.csv"))
n0 = len(c)
c = c.drop_duplicates(subset="CustomerID", keep="first")
log.append(("Customers", "Duplicate CustomerID rows removed", n0 - len(c)))

before_vals = c["Region"].copy()
c["Region"] = c["Region"].str.strip().str.title()
log.append(("Customers", "Region text standardised (trim + title case)", int((before_vals != c["Region"]).sum())))

bad_score = ~c["CreditScore"].between(300, 850)
log.append(("Customers", "Invalid CreditScore (outside 300-850) set to median and flagged", int(bad_score.sum())))
med_score = int(c.loc[~bad_score, "CreditScore"].median())
c["CreditScoreImputed"] = bad_score.astype(int)
c.loc[bad_score, "CreditScore"] = med_score

miss_inc = c["AnnualIncome"].isna()
log.append(("Customers", "Missing AnnualIncome filled with median of EmploymentType and flagged", int(miss_inc.sum())))
c["AnnualIncomeImputed"] = miss_inc.astype(int)
c["AnnualIncome"] = c["AnnualIncome"].fillna(c.groupby("EmploymentType")["AnnualIncome"].transform("median")).round(-3).astype(int)
c.to_csv(os.path.join(OUT, "Clean_Customers.csv"), index=False)

# -------------------------------------------------------------------- Loans
l = pd.read_csv(os.path.join(RAW, "Loans.csv"), dtype={"InterestRate": str})
n0 = len(l)
l = l.drop_duplicates(subset="LoanID", keep="first")
log.append(("Loans", "Duplicate LoanID rows removed", n0 - len(l)))
pct = l["InterestRate"].str.contains("%")
log.append(("Loans", "InterestRate stored as text with '%' converted to number", int(pct.sum())))
l["InterestRate"] = l["InterestRate"].str.replace("%", "", regex=False).astype(float)
orphans = ~l["CustomerID"].isin(c["CustomerID"])
log.append(("Loans", "Loans with no matching customer (orphans)", int(orphans.sum())))
l = l[~orphans]
l.to_csv(os.path.join(OUT, "Clean_Loans.csv"), index=False)

# ----------------------------------------------------------------- Payments
p = pd.read_csv(os.path.join(RAW, "Payments.csv"))
n0 = len(p)
p = p[p["LoanID"].isin(l["LoanID"])].drop_duplicates(subset="PaymentID")
log.append(("Payments", "Rows dropped (orphan loan or duplicate PaymentID)", n0 - len(p)))
p.to_csv(os.path.join(OUT, "Clean_Payments.csv"), index=False)

# ----------------------------------------------------------------- Defaults
d = pd.read_csv(os.path.join(RAW, "Defaults.csv"))
n0 = len(d)
d = d[d["LoanID"].isin(l["LoanID"])].drop_duplicates(subset="LoanID")
log.append(("Defaults", "Rows dropped (orphan loan or duplicate)", n0 - len(d)))
d.to_csv(os.path.join(OUT, "Clean_Defaults.csv"), index=False)

# ------------------------------------------------------------------- report
lines = ["# Data Cleaning Log", "",
         "Generated by `clean_dataset.py`. Counts are rows (or variants) affected.", "",
         "| Table | Issue / action | Count |", "|---|---|---:|"]
lines += [f"| {t} | {a} | {n} |" for t, a, n in log]
lines += ["", "## Final row counts", "", "| Table | Rows |", "|---|---:|",
          f"| Clean_Customers | {len(c):,} |", f"| Clean_Loans | {len(l):,} |",
          f"| Clean_Payments | {len(p):,} |", f"| Clean_Defaults | {len(d):,} |"]
with open(os.path.join(HERE, "Cleaning Log.md"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
